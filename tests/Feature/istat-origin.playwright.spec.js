import {test, expect, BASE_URL} from '../Support/playwright.js';
for (const width of [1440, 768, 390]) test(`ISTAT dati origine e configurazione a ${width}px`, async ({page}, info) => {
    await page.setViewportSize({width, height:1000});
    const refs = await (await page.goto(`${BASE_URL}/istat-origin.json`)).json();
    await page.goto(`${BASE_URL}/login`);
    await page.locator('[name=login]').fill('istat-origin-admin');
    await page.locator('[name=password]').fill('Password-istat-fixture-123!');
    await page.getByRole('button', {name:'Entra', exact:true}).click();
    await expect(page).not.toHaveURL(/\/login$/);
    expect((await page.goto(`${BASE_URL}/struttura?sid=${refs.struttura_id}`)).status()).toBe(200);
    await expect(page.locator('[name=camere_disponibili]')).toHaveValue('10');
    await expect(page.locator('[name=letti_disponibili]')).toHaveValue('20');
    await expect(page.locator('#tipoAperturaSwitch')).toBeChecked();
    await page.locator('#tipoAperturaSwitch').uncheck();
    await expect(page.locator('[name=data_apertura]')).toBeEnabled();
    await expect(page.locator('[name=data_chiusura]')).toBeEnabled();
    await page.locator('[name=camere_disponibili]').scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath(`origine-capacita-${width}.png`)});
    await page.reload();
    await expect(page.locator('#tipoAperturaSwitch')).toBeChecked();
    expect((await page.goto(`${BASE_URL}/schedine/${refs.schedina_id}/modifica?sid=${refs.struttura_id}`)).status()).toBe(200);
    await expect(page.locator('[name=istat_tipo_turismo]')).toHaveValue('OTHER');
    await expect(page.locator('[name=istat_mezzo_trasporto]')).toHaveValue('AUTO');
    await page.getByText('Tipo turismo',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath(`origine-statistica-${width}.png`)});
    await page.getByRole('tab',{name:'Residenza / Doc.',exact:true}).click();
    await expect(page.locator('[name=or_country] option:checked')).toHaveText('ITALIA');
    await expect(page.locator('#schedina-step-res-pane')).toBeVisible();
    await expect(page.locator('#schedina-step-res-pane')).toHaveCSS('opacity', '1');
    await page.locator('[name=or_country]').scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath(`origine-residenza-${width}.png`)});
    await page.getByRole('tab',{name:'Componenti',exact:true}).click();
    await expect(page.locator('#schedina-step-comp-pane')).toContainText('Minore Fixture');
    await expect(page.locator('#schedina-step-comp-pane')).toBeVisible();
    await expect(page.locator('#schedina-step-comp-pane')).toHaveCSS('opacity', '1');
    await page.locator('#schedina-step-comp-pane').scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath(`origine-componenti-${width}.png`)});
    await page.goto(`${BASE_URL}/istat-tabella-a?mese=2026-04`);
    await page.locator('#istat-codice').fill('');
    await page.getByRole('button',{name:'Salva configurazione',exact:true}).click();
    await expect(page.getByRole('dialog')).toContainText('Campi obbligatori mancanti');
    await page.getByRole('button',{name:'OK',exact:true}).click();
    await page.locator('#istat-codice').fill('TEST-FIXTURE');
    await page.getByRole('button',{name:'Salva configurazione',exact:true}).click();
    await page.getByRole('button',{name:'Sì, salva',exact:true}).click();
    await page.getByRole('button',{name:'OK',exact:true}).click();
    await expect(page.locator('body')).toContainText('Configurazione Ross1000 salvata. Nessuna richiesta effettuata.');
    await expect(page.locator('#istat-username')).toHaveValue('');
    await expect(page.locator('#istat-password')).toHaveValue('');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
