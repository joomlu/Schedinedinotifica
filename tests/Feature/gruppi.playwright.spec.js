test('Gruppi: rinomina dal formulario, associazioni visibili e isolamento tra due strutture', async ({page}) => {
 const ids=await (await page.request.get(`${BASE_URL}/gruppi-fixture-ids.json`)).json();
 const login=async(role)=>{await page.goto(`${BASE_URL}/login`);await page.locator('input[name="login"]').fill(`fixture-${role}`);await page.locator('input[name="password"]').fill('Password-fixture-123!');await page.getByRole('button',{name:'Entra',exact:true}).click();await expect(page).not.toHaveURL(/\/login$/);};
 await login('super_admin'); await page.goto(`${BASE_URL}/gruppi?q=Business`);
 const row=page.locator('tr[data-nome="Business"]'); const id=await row.getAttribute('data-id');
 await row.locator('[data-bs-toggle="modal"]').click();
 const modal=page.locator(`#modalGruppoEdit${id}`);await expect(modal).toBeVisible();
 await modal.locator('[name="nome"]').fill('Businessprivatobrowser'); await modal.getByRole('button',{name:'Salva',exact:true}).click();
 await page.getByRole('button',{name:'Sì, modifica',exact:true}).click();
 await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'OK',exact:true}).click()]);
 await page.getByRole('button',{name:'OK',exact:true}).click();
 await page.goto(`${BASE_URL}/clienti/${ids.cliente}/modifica`);
 await expect(page.locator('#customer-group')).toHaveValue('Businessprivatobrowser');
 await page.goto(`${BASE_URL}/schedine/${ids.schedina}/modifica`);
 await expect(page.locator('#schedina-customer-group')).toHaveValue('Businessprivatobrowser');
 await page.goto(`${BASE_URL}/logout`); await login('struttura_user');
 await page.goto(`${BASE_URL}/gruppi?q=Businessprivatobrowser`);
 await expect(page.locator('#gruppiTable tbody tr.data-row')).toHaveCount(0);
 await page.goto(`${BASE_URL}/gruppi?q=Business`);
 await expect(page.locator('tr[data-nome="Business"]')).toHaveCount(1);
 const token=await page.locator('tr[data-nome="Business"] input[name="_token"]').getAttribute('value');
 const response=await page.request.put(`${BASE_URL}/gruppi/${id}`,{form:{nome:'Attacco browser',livello:'1',_token:token}});
 expect(response.status()).toBe(404);
});
