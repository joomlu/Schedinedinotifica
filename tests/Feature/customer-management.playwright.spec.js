import fs from 'node:fs';
import path from 'node:path';
import {test, expect, BASE_URL} from '../Support/playwright.js';
test.use({headless:true});
for (const width of [1440, 390]) test(`Gestione cliente, tassa e stampa a ${width}`, async ({page}, testInfo) => {
 test.setTimeout(90000);
 const evidence=fs.mkdtempSync('/tmp/schedine-clienti-evidenze-');
 console.log('EVIDENZE_SINTETICHE='+evidence);
 await page.setViewportSize({width,height:900});
 const nomeAggiornato=width===1440?'Cliente Aggiornato Desktop':'Cliente Aggiornato Mobile';
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${BASE_URL}/login`);
 await page.locator('[name="login"]').fill('fixture-super_admin');
 await page.locator('[name="password"]').fill('Password-fixture-123!');
 await page.getByRole('button',{name:'Entra',exact:true}).click();
 await expect(page).not.toHaveURL(/\/login$/);
 await page.goto(`${BASE_URL}/superadmin/tassa/configurazione`);
 await expect(page.locator('#sidebarQa')).toHaveCount(0);
 await expect(page.locator('a[href*="/qa"]')).toHaveCount(0);
 for(const id of ['profilo-territoriale','verifiche-fonti','documentazione-tassa','note-esenzioni']) await expect(page.locator(`#${id}`)).toBeVisible();
 await expect(page.getByText('Contesto territoriale',{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:path.join(evidence,`tassa-${width}.png`),fullPage:true});
 if(await page.getByRole('button',{name:/Struttura: Hotel Browser(?! B)/}).count()===0){
   await page.getByRole('button',{name:/Struttura:/}).click();
   await page.getByRole('button',{name:'Hotel Browser',exact:true}).click();
   await page.waitForLoadState('networkidle');
 }
 await page.goto(`${BASE_URL}/clienti`);await page.waitForLoadState('networkidle');
 await page.locator('#clientiSearch').fill('Sintetico');
 await page.locator('#clientiSearch').press('Enter');
 await expect.poll(()=>new URL(page.url()).searchParams.get('q')).toBe('Sintetico');
 await expect(page.getByRole('link',{name:'Apri scheda cliente',exact:true})).toHaveCount(1);
 await expect(page.locator('#clientiTable tbody')).toContainText('Sintetico');
 await page.locator('#clientiOrdine').selectOption('cognome');
 await expect(page).toHaveURL(/ordine=cognome/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.getByRole('link',{name:'Apri scheda cliente',exact:true}).click();
 await expect(page.locator('[name="name"]')).toHaveValue(/^Cliente/);
 await page.waitForLoadState('networkidle');
 await expect(page.locator('[name="type_cliente"]')).toHaveValue('Richiesta');
 await page.locator('[name="name"]').fill(nomeAggiornato);
 await page.getByRole('button',{name:/Salva a cliente/}).first().click();
 console.log('VALIDAZIONE_SINTETICA',await page.locator('form.form-steps').evaluate(form=>Array.from(form.elements).filter(f=>f.willValidate&&!f.validity.valid).map(f=>({nome:f.name,errore:f.validationMessage}))));
 await expect(page.getByRole('button',{name:'Sì, modifica',exact:true})).toBeVisible({timeout:10000});
 await page.getByRole('button',{name:'Sì, modifica',exact:true}).click();
 await page.getByRole('button',{name:'OK',exact:true}).click();
 await expect(page).toHaveURL(/\/clienti$/);
 await page.waitForLoadState('networkidle');
 const avviso=page.getByRole('button',{name:'OK',exact:true});
 if(await avviso.isVisible()) await avviso.click();
 await page.locator('#clientiSearch').fill(nomeAggiornato);
 await page.locator('#clientiSearch').press('Enter');
 await expect.poll(()=>new URL(page.url()).searchParams.get('q')).toBe(nomeAggiornato);
 await expect(page.getByRole('link',{name:'Apri scheda cliente',exact:true})).toHaveCount(1);
 await expect(page.locator('#clientiTable tbody')).toContainText(nomeAggiornato);
 await page.getByRole('link',{name:'Apri scheda cliente',exact:true}).click();
 await expect(page.locator('[name="name"]')).toHaveValue(nomeAggiornato);
 const popupEvent=page.waitForEvent('popup');
 await page.getByRole('link',{name:'Stampa scheda completa',exact:true}).click();
 const print=await popupEvent;
 await expect(print.locator('body')).toContainText(nomeAggiornato);
 await expect(print.locator('body')).toContainText('Azienda');
 await expect(print.locator('body')).toContainText('Storico soggiorni completo');
 await print.emulateMedia({media:'print'});
 await expect(print.locator('.print-actions')).toBeHidden();
 await print.pdf({path:path.join(evidence,`scheda-${width}.pdf`),format:'A4',printBackground:true});
 await print.screenshot({path:path.join(evidence,`stampa-${width}.png`),fullPage:true});
 await print.close();
 expect(errors).toEqual([]);
});

for(const role of ['admin','proprietario']) test(`Navigazione e dinieghi browser ${role}`,async({page})=>{
 await page.goto(`${BASE_URL}/login`);
 await page.locator('[name="login"]').fill(`fixture-${role}`);
 await page.locator('[name="password"]').fill('Password-fixture-123!');
 await page.getByRole('button',{name:'Entra',exact:true}).click();
 await expect(page).not.toHaveURL(/\/login$/);
 await page.goto(`${BASE_URL}/${role==='admin'?'admin/proprietari':'proprietario/strutture'}`);
 await expect(page.locator('body')).toContainText(role==='admin'?'Proprietario Browser':'Hotel Browser');
 await expect(page.locator('a[href*="/qa"]')).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 const denied=await page.goto(`${BASE_URL}/superadmin/tassa/configurazione`);
 expect(denied.status()).toBe(403);
});
