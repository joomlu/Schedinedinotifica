import {test, expect, BASE_URL} from '../Support/playwright.js';
for (const width of [1440, 768, 390]) {
    test(`Calendario intuitivo: viste, dettaglio, note e attività a ${width}px`, async ({page}) => {
        await page.setViewportSize({width, height: 1000});
        const errors = [];
        page.on('pageerror', e => errors.push(e.message));
        await page.goto(`${BASE_URL}/login`);
        await page.locator('[name="login"]').fill('calendario-ui');
        await page.locator('[name="password"]').fill('Fixture-calendario-123!');
        await page.getByRole('button', {name: /Accedi|Entra/i}).click();
        await page.getByRole('button', {name: 'Sì, salva', exact: true}).click();
        const login = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/login');
        await page.getByRole('button', {name: 'OK', exact: true}).click();
        await login;
        await page.waitForLoadState('load');
        const r = await page.goto(`${BASE_URL}/calendario?giorno=2026-10-30&mese=2026-10&vista=month`);
        expect(r.status()).toBe(200);
        await expect(page.locator('.calendar-day')).toHaveCount(35);
        await expect(page.getByRole('navigation', {name: 'Vista calendario'})).toBeVisible();
        await expect(page.getByText('Tutte le strutture', {exact: true})).toHaveCount(0);
        await expect(page.getByRole('link', {name: 'Agenda', exact: true})).toHaveCount(0);
        await expect(page.locator('.calendar-day[data-date="2026-10-30"]')).toContainText('Informazioni');
        await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.screenshot({path: `/tmp/calendario-mese-${width}.png`, fullPage: true});
        if (width === 1440) {
            await page.evaluate(() => document.documentElement.setAttribute('data-bs-theme', 'dark'));
            await page.screenshot({path: '/tmp/calendario-mese-scuro.png', fullPage: true});
            await page.evaluate(() => document.documentElement.setAttribute('data-bs-theme', 'light'));
        }
        await page.locator('.calendar-day[data-date="2026-10-30"]').focus();
        await page.keyboard.press('Enter');
        const dialog = page.locator('#calendarDayModal');
        await expect(dialog).toBeVisible();
        await expect(dialog).toContainText('Verificare documenti Rossi');
        await expect(dialog.locator('.calendar-description').first()).not.toBeVisible();
        await dialog.locator('summary').filter({hasText: 'Arrivo: Mario'}).click();
        await expect(dialog).toContainText('Laura Componente sintetico');
        await expect(dialog.getByRole('link', {name: 'Apri soggiorno'})).toBeVisible();
        await page.screenshot({path: `/tmp/calendario-giorno-${width}.png`, fullPage: false});
        await dialog.locator('summary').filter({hasText: 'Verificare documenti Rossi'}).click();
        await dialog.locator('details').filter({has: page.locator('summary', {hasText: 'Verificare documenti Rossi'})}).getByRole('button', {name: 'Modifica', exact: true}).click();
        const edit = page.locator('.modal.show');
        await expect(edit).toContainText('Modifica annotazione');
        await edit.getByRole('button', {name: 'Annulla', exact: true}).click();
        await expect(page.locator('.modal.show')).toHaveCount(0);
        await page.locator('.calendar-day[data-date="2026-10-30"]').click();
        await dialog.getByRole('button', {name: 'Aggiungi a questo giorno'}).click();
        const form = page.locator('#modalNuovoEvento');
        await expect(form).toBeVisible();
        await expect(form.locator('[name="data_evento"]')).toHaveValue('2026-10-30');
        await form.locator('#select2-modalNuovoEventoTipo-container').click();
        await page.getByRole('option', {name: 'Informazioni · nota', exact: true}).click();
        await form.locator('[name="titolo"]').fill(`Nota sintetica ${width}`);
        await form.locator('[name="descrizione"]').fill('Comunicazione interna senza invio.');
        await form.getByRole('button', {name: 'Salva', exact: true}).click();
        await expect(page).toHaveURL(/vista=month/);
        const alert = page.getByRole('button', {name: 'OK', exact: true});
        await expect(alert).toBeVisible();
        await alert.click();
        await expect(dialog).toBeVisible();
        await expect(dialog).toContainText(`Nota sintetica ${width}`);
        await dialog.getByRole('button', {name: 'Chiudi', exact: true}).last().click();
        await page.getByRole('link', {name: 'Da fare', exact: true}).click();
        await expect(page).toHaveURL(/categoria=attivita/);
        await page.waitForLoadState('load');
        await page.locator('.calendar-day[data-date="2026-10-30"]').click();
        const task = dialog.locator('.calendar-entry').filter({hasText: 'Verificare documenti Rossi'});
        await task.locator('summary').click();
        await task.getByRole('button', {name: 'Segna completata', exact: true}).click();
        await page.getByRole('button', {name: 'OK', exact: true}).click();
        const done = dialog.locator('.calendar-entry').filter({hasText: 'Verificare documenti Rossi'});
        await done.locator('summary').click();
        await expect(done.getByRole('button', {name: 'Riapri attività'})).toBeVisible();
        await done.getByRole('button', {name: 'Riapri attività'}).click();
        await page.getByRole('button', {name: 'OK', exact: true}).click();
        await dialog.getByRole('button', {name: 'Chiudi', exact: true}).last().click();
        for (const vista of ['Settimana', 'Giorno', 'Mese']) {
    await page.getByRole('link', {name: vista, exact: true}).click();
            await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        }
        await page.getByRole('link', {name: 'Periodo successivo'}).click();
        await expect(page).toHaveURL(/mese=2026-11/);
        await page.locator('.calendar-filters > summary').click();
        const date = page.locator('#calendar-date');
        await expect(date).toHaveAttribute('data-ui', 'datepicker');
        await expect(page.locator('#calendar-dateDisplay')).toHaveValue('01/11/2026');
        await page.locator('#calendar-dateDisplay').click();
        await expect(page.locator('.flatpickr-calendar.open')).toBeVisible();
        await page.keyboard.press('Escape');
        await page.getByRole('link', {name: 'Storico annotazioni', exact: true}).click();
        await expect(page.locator('#calendar-history-state')).toHaveAttribute('data-ui', 'select-search');
        await expect(page.locator('h6').filter({hasText: '30 ottobre 2026'})).toBeVisible();
        await expect(page.getByText('Tutte le strutture', {exact: true})).toHaveCount(0);
        await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.screenshot({path: `/tmp/calendario-storico-${width}.png`, fullPage: true});
        expect(errors).toEqual([]);
    });
}
