import {test, expect, BASE_URL} from '../Support/playwright.js';
for (const width of [1440, 768, 390]) {
  test(`Configurazione unificata e salvataggi indipendenti a ${width}px`, async ({page}, info) => {
    test.setTimeout(120000);
    await page.setViewportSize({width, height:900});
    await page.goto(`${BASE_URL}/login`);
    await page.getByLabel(/Nome di accesso o email/i).fill('anagrafica-admin');
    await page.getByLabel(/Password personale/i).fill('Password-anagrafica-sintetica-123!');
    await page.getByRole('button', {name:/^Accedi$/i}).click();
    await page.getByRole('button', {name:'Sì, salva',exact:true}).click();
    const accesso=page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname==='/login');
    await page.getByRole('button', {name:'OK',exact:true}).click();
    await accesso;
    await page.waitForLoadState('load');
    const ids=await (await page.request.get(`${BASE_URL}/anagrafiche-fixture.json`)).json();
    await page.goto(`${BASE_URL}/struttura?sid=${ids.struttura}`);
    await expect(page.getByRole('link',{name:'Questura / Alloggiati Web',exact:true,includeHidden:true})).toHaveCount(0);
    await expect(page.getByLabel('Profilo Alloggiati Web',{exact:true})).toBeVisible();
    await expect(page.getByLabel('ID appartamento Alloggiati Web',{exact:true})).toBeVisible();
    const original=await page.locator('[name=nome_struttura]').inputValue();
    await page.locator('[name=nome_struttura]').fill('');
    await page.getByLabel('Codice struttura Ross1000',{exact:true}).fill('');
    await page.getByRole('button',{name:'Salva configurazione',exact:true}).click();
    await expect(page.getByText('Completa il campo richiesto: Codice struttura Ross1000',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'OK',exact:true}).click();
    await page.getByLabel('Codice struttura Ross1000',{exact:true}).fill(`CODICE-SINTETICO-${width}`);
    await page.getByLabel('Username WebService',{exact:true}).fill('UTENTE-SINTETICO');
    await page.getByLabel('Password WebService',{exact:true}).fill('SEGRETO-SINTETICO');
    await page.getByRole('button',{name:'Salva configurazione',exact:true}).click();
    await page.getByRole('button',{name:/^Sì,/}).click();
    await page.getByRole('button',{name:'OK',exact:true}).click();
    await expect(page).toHaveURL(/\/struttura\?struttura_id=\d+#configurazione-ross1000$/);
    await expect(page.locator('[name=nome_struttura]')).toHaveValue(original);
    await expect(page.getByLabel('Username WebService',{exact:true})).toHaveValue('');
    await expect(page.getByLabel('Password WebService',{exact:true})).toHaveValue('');
    const flash=page.getByRole('button',{name:'OK',exact:true});
    await expect(page.getByRole('dialog',{name:'Operazione completata',exact:true})).toBeVisible();
    await flash.click();
    await page.getByLabel('Codice struttura Ross1000',{exact:true}).fill('');
    await page.getByLabel('Profilo Alloggiati Web',{exact:true}).selectOption('appartamenti');
    await page.getByLabel('ID appartamento Alloggiati Web',{exact:true}).fill('000123');
    await page.getByRole('button',{name:'Salva',exact:true}).click();
    await page.getByRole('button',{name:/^Sì,/}).click();
    await page.getByRole('button',{name:'OK',exact:true}).click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByLabel('ID appartamento Alloggiati Web',{exact:true})).toHaveValue('123');
    await expect(page.getByLabel('Codice struttura Ross1000',{exact:true})).toHaveValue(`CODICE-SINTETICO-${width}`);
    await expect(page.getByRole('dialog',{name:'Operazione completata',exact:true})).toBeVisible();
    await flash.click();
    await page.locator('#configurazione-questura').screenshot({path:info.outputPath(`riferimenti-${width}.png`)});
    const size=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
    expect(size.scroll).toBeLessThanOrEqual(size.width+1);
    await page.goto(`${BASE_URL}/istat-tabella-a?sid=${ids.struttura}`);
    await expect(page.getByLabel('Password WebService',{exact:true})).toHaveCount(0);
    await expect(page.getByRole('link',{name:'Impostazioni Ross1000 della struttura',exact:true})).toBeVisible();
  });
}
